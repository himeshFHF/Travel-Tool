import { test, expect } from "@playwright/test";

test("new trips retain separate plans and documents across navigation and reload",async({page})=>{
  const title=`January weekend ${Date.now()}`;
  await page.goto("/signin-with-chatgpt?return_to=%2F%23trips");
  await page.getByRole("button",{name:"New trip",exact:true}).click();
  await page.getByLabel("Trip name",{exact:true}).fill(title);
  await page.getByLabel("Start date",{exact:true}).fill("2027-01-02");
  await page.getByLabel("End date",{exact:true}).fill("2027-01-04");
  await page.getByRole("button",{name:"Create trip",exact:true}).click();
  await expect(page.getByRole("heading",{name:title,exact:true})).toBeVisible();
  const hash=new URL(page.url()).hash;
  const id=new URLSearchParams(hash.split("?")[1]).get("trip")!;
  expect(id).toBeTruthy();
  await expect(page.getByRole("button",{name:/Sat 2/})).toBeVisible();
  await page.getByRole("button",{name:"Add a stop",exact:true}).first().click();
  await page.getByLabel("Stop title",{exact:true}).fill("A winter museum visit");
  await page.getByRole("button",{name:"Save stop",exact:true}).click();
  await expect(page.getByRole("button",{name:"A winter museum visit",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Add documents",exact:true}).click();
  await page.locator("input[type=file]").setInputFiles({name:"new-trip-note.txt",mimeType:"text/plain",buffer:Buffer.from("Museum confirmation for our January trip.")});
  await page.getByRole("button",{name:"Save document",exact:true}).click();
  await expect(page.getByText("Original saved.",{exact:false})).toBeVisible();
  await page.getByRole("button",{name:"Done",exact:true}).click();
  await page.getByRole("button",{name:/Documents/}).first().click();
  const link=page.getByRole("link",{name:/new-trip-note.txt/});
  await expect(link).toBeVisible();
  expect(await link.getAttribute("href")).toContain(`tripId=${id}`);
  const response=await page.request.get((await link.getAttribute("href"))!);
  expect(response.status()).toBe(200);
  await page.getByRole("link",{name:"My trips",exact:true}).click();
  await expect(page.getByRole("link",{name:`Open ${title}`})).toBeVisible();
  await page.getByRole("link",{name:"Open California escape",exact:true}).click();
  await expect(page.getByRole("heading",{name:"California, together.",exact:true})).toBeVisible();
  const seed=await(await page.request.get("/api/trip")).json();
  expect(seed.documents.some((d:any)=>d.name==="new-trip-note.txt")).toBe(false);
  expect(seed.trip.events.some((s:any)=>s.title==="A winter museum visit")).toBe(false);
  await page.goBack();
  await page.getByRole("link",{name:`Open ${title}`} ).click();
  await page.reload();
  await expect(page.getByRole("button",{name:"A winter museum visit",exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:"test-results/new-trip-mobile.png",fullPage:true});
});
